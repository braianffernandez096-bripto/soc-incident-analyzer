"""MITRE ATT&CK enrichment: technique names and links, a matrix grouped by tactic and a Navigator layer export.

Source of truth: backend/data/attack_techniques.json, generated by scripts/build_attack_data.py from the official
MITRE ATT&CK STIX data (only the techniques the detection rules reference). Nothing here calls the network.

The mapping is ORIENTATIVE: the deterministic rules suggest techniques that are consistent with the evidence in the
logs; they are not proof that an adversary used them, and they never change a finding's severity.

User-facing labels are in Spanish on purpose (product language); code and comments are in English.
"""
from __future__ import annotations

import json
from functools import lru_cache
from pathlib import Path

from . import detection as D

DATA_FILE = Path(__file__).parent / "data" / "attack_techniques.json"
URL_BASE = "https://attack.mitre.org/techniques/"

# Kill-chain order of the Enterprise tactics (ATT&CK v20 names `stealth` what used to be `defense-evasion`).
TACTIC_ORDER = [
    "reconnaissance", "resource-development", "initial-access", "execution", "persistence", "privilege-escalation",
    "stealth", "defense-impairment", "credential-access", "discovery", "lateral-movement", "collection",
    "command-and-control", "exfiltration", "impact",
]
TACTIC_ES = {
    "reconnaissance": "Reconocimiento", "resource-development": "Desarrollo de recursos",
    "initial-access": "Acceso inicial", "execution": "Ejecución", "persistence": "Persistencia",
    "privilege-escalation": "Escalamiento de privilegios", "stealth": "Sigilo (evasión de defensas)",
    "defense-impairment": "Deterioro de defensas", "credential-access": "Acceso a credenciales",
    "discovery": "Descubrimiento", "lateral-movement": "Movimiento lateral", "collection": "Recolección",
    "command-and-control": "Comando y control", "exfiltration": "Exfiltración", "impact": "Impacto",
}
SEV_COLOR = {"Crítico": "#b3261e", "Alto": "#e07b00", "Medio": "#d4b100", "Bajo": "#3f8f68"}

NAVIGATOR_VERSION = "5.1.0"
LAYER_VERSION = "4.5"


@lru_cache(maxsize=1)
def data() -> dict:
    return json.loads(DATA_FILE.read_text(encoding="utf-8"))


def technique_url(tid: str) -> str:
    return URL_BASE + tid.replace(".", "/") + "/"


def technique_name(tid: str) -> str:
    return data()["techniques"].get(tid, {}).get("name", "")


def label(tid: str) -> str:
    """'T1110 Brute Force' (just the ID when the technique is not in the bundled data)."""
    name = technique_name(tid)
    return f"{tid} {name}" if name else tid


def build_matrix(findings: list[D.Finding]) -> dict:
    """Group the techniques cited by the findings under the official tactics they belong to."""
    d = data()
    per_tech: dict[str, dict] = {}
    for f in findings:
        for tid in f.mitre:
            t = per_tech.setdefault(tid, {"finding_ids": [], "severity": "Bajo"})
            if f.id not in t["finding_ids"]:
                t["finding_ids"].append(f.id)
            t["severity"] = D.max_sev([t["severity"], f.severity])
    columns: dict[str, list[dict]] = {}
    unknown = []
    for tid, t in per_tech.items():
        info = d["techniques"].get(tid)
        if not info:
            unknown.append(tid)
            continue
        cell = {"id": tid, "name": info["name"], "url": technique_url(tid), "count": len(t["finding_ids"]),
                "severity": t["severity"], "finding_ids": t["finding_ids"]}
        for tac in info["tactics"]:
            columns.setdefault(tac, []).append(cell)
    tactics = []
    for key in TACTIC_ORDER:
        if key not in columns:
            continue
        cells = sorted(columns[key], key=lambda c: (-D.SEV_ORDER[c["severity"]], -c["count"], c["id"]))
        tactics.append({"key": key, "id": d["tactics"].get(key, {}).get("id", ""),
                        "name": d["tactics"].get(key, {}).get("name", key), "name_es": TACTIC_ES.get(key, key),
                        "techniques": cells})
    return {
        "version": d["attack_version"], "domain": d["domain"], "tactics": tactics,
        "techniques": {tid: {"name": d["techniques"][tid]["name"], "url": technique_url(tid)}
                       for tid in per_tech if tid in d["techniques"]},
        "techniques_total": len(per_tech) - len(unknown), "unknown": sorted(unknown),
        "findings_without_mapping": sum(1 for f in findings if not f.mitre),
    }


def navigator_layer(matrix: dict, name: str) -> dict:
    """ATT&CK Navigator layer (format 4.5): one entry per technique and tactic, coloured by the highest severity."""
    entries = []
    for tac in matrix["tactics"]:
        for c in tac["techniques"]:
            entries.append({
                "techniqueID": c["id"], "tactic": tac["key"], "score": c["count"], "color": SEV_COLOR[c["severity"]],
                "comment": f"Hallazgos: {', '.join(c['finding_ids'])} · criticidad máxima: {c['severity']}",
                "enabled": True, "metadata": [], "links": [], "showSubtechniques": False,
            })
    top = max((e["score"] for e in entries), default=1)
    return {
        "name": name[:120],
        "versions": {"attack": matrix["version"].split(".")[0], "navigator": NAVIGATOR_VERSION, "layer": LAYER_VERSION},
        "domain": matrix["domain"],
        "description": "Técnicas ATT&CK orientativas sugeridas por las reglas de SOC Incident Analyzer. "
                       "Son consistentes con la evidencia de los logs; no prueban por sí solas el uso de la técnica. "
                       "El color indica la criticidad máxima de los hallazgos asociados.",
        "sorting": 0,
        "layout": {"layout": "side", "aggregateFunction": "average", "showID": True, "showName": True,
                   "showAggregateScores": False, "countUnscored": False, "expandedSubtechniques": "annotated"},
        "hideDisabled": False, "techniques": entries,
        "gradient": {"colors": ["#ffe766", "#ff6666"], "minValue": 0, "maxValue": top},
        "legendItems": [{"label": f"Criticidad máxima: {s}", "color": c} for s, c in SEV_COLOR.items()],
        "metadata": [], "links": [], "showTacticRowBackground": False, "tacticRowBackground": "#dddddd",
        "selectTechniquesAcrossTactics": True, "selectSubtechniquesWithParent": False, "selectVisibleTechniques": False,
    }
